import { isAbsolute, win32, posix } from "node:path";

export const COMFY_PATH_SCHEMA_VERSION = 1;
const LABEL = /^[a-zA-Z][a-zA-Z0-9_]{0,63}$/;
const CATEGORY = /^[a-zA-Z][a-zA-Z0-9_]{0,63}$/;
const RESERVED = new Set(["base_path", "is_default"]);
const MAX_ROOTS = 24;
const MAX_PATHS_PER_CATEGORY = 32;

function plainObject(x) {
  return !!x && typeof x === "object" && !Array.isArray(x) &&
    (Object.getPrototypeOf(x) === Object.prototype || Object.getPrototypeOf(x) === null);
}
function cleanAbsolutePath(value) {
  if (typeof value !== "string" || !value.trim() || value.length > 4096 ||
      /[\r\n\0]/.test(value)) throw new Error("INVALID_BASE_PATH");
  const normalized = value.trim().replace(/\\/g, "/").replace(/\/+$/, "");
  if (!(isAbsolute(normalized) || win32.isAbsolute(value))) throw new Error("ABSOLUTE_PATH_REQUIRED");
  if (normalized === "") throw new Error("INVALID_BASE_PATH");
  return normalized;
}
function cleanRelativePath(value) {
  if (typeof value !== "string" || !value.trim() || value.length > 1024 ||
      /[\r\n\0]/.test(value)) throw new Error("INVALID_RELATIVE_PATH");
  const normalized = value.trim().replace(/\\/g, "/").replace(/\/+$/, "");
  if (normalized === "." || normalized === "" || normalized.startsWith("/") ||
      /^[a-zA-Z]:/.test(normalized) ||
      normalized.split("/").some(part => !part || part === "." || part === "..")) {
    throw new Error("INVALID_RELATIVE_PATH");
  }
  return normalized;
}

export function validateComfyPathManifest(raw) {
  if (!plainObject(raw) || raw.schemaVersion !== COMFY_PATH_SCHEMA_VERSION ||
      !Array.isArray(raw.roots) || !raw.roots.length || raw.roots.length > MAX_ROOTS ||
      Object.keys(raw).some(k => !["schemaVersion", "roots"].includes(k))) {
    throw new Error("INVALID_MODEL_PATH_MANIFEST");
  }
  const seenIds = new Set();
  const roots = [];
  for (const source of raw.roots) {
    if (!plainObject(source) || !LABEL.test(source.id ?? "") ||
        seenIds.has(source.id) || !plainObject(source.categories) ||
        Object.keys(source).some(k => !["id", "basePath", "categories"].includes(k))) {
      throw new Error("INVALID_MODEL_ROOT");
    }
    seenIds.add(source.id);
    const basePath = cleanAbsolutePath(source.basePath);
    const categories = Object.create(null);
    const keys = Object.keys(source.categories);
    if (!keys.length || keys.length > 100) throw new Error("INVALID_MODEL_CATEGORIES");
    for (const category of keys) {
      if (!CATEGORY.test(category) || RESERVED.has(category)) throw new Error("INVALID_MODEL_CATEGORY");
      const paths = source.categories[category];
      if (!Array.isArray(paths) || !paths.length || paths.length > MAX_PATHS_PER_CATEGORY)
        throw new Error("INVALID_MODEL_PATHS");
      const normalized = paths.map(cleanRelativePath);
      if (new Set(normalized).size !== normalized.length) throw new Error("DUPLICATE_MODEL_PATH");
      categories[category] = normalized;
    }
    roots.push({ id: source.id, basePath, categories });
  }
  return { schemaVersion: COMFY_PATH_SCHEMA_VERSION, roots };
}

function fullPath(basePath, rel) {
  return (basePath + "/" + rel).replace(/\/+/g, "/");
}

export function listComfyModelPaths(manifest) {
  const valid = validateComfyPathManifest(manifest);
  return valid.roots.flatMap(root => Object.entries(root.categories)
    .flatMap(([category, relative]) => relative.map(item => ({
      rootId: root.id, category, path: fullPath(root.basePath, item)
    }))));
}

export function generateComfyExtraPathsYaml(manifest) {
  const valid = validateComfyPathManifest(manifest);
  const rows = [
    "# Generated by EFSS BellekPad. Do not include private absolute paths in Git.",
    "# Original source: local model-paths JSON; no models are copied.",
    "# Install as extra_model_paths.yaml in the ComfyUI config location.",
    ""
  ];
  for (const root of valid.roots) {
    rows.push("efss_" + root.id + ":");
    rows.push("  base_path: " + JSON.stringify(root.basePath));
    for (const [category, paths] of Object.entries(root.categories)) {
      rows.push("  " + category + ": |");
      for (const path of paths) rows.push("    " + path);
    }
    rows.push("");
  }
  return rows.join("\n");
}
